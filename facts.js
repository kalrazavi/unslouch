// A stable pick: the same seed always returns the same line, so text does not flicker on redraw.
export function fact(key, seed) {
  const list = FACTS[key] || FACTS.all;
  let h = 7;
  for (const c of String(seed)) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return list[h % list.length];
}
